"""
generate_pipeline.py: writes infrastructure/cloudformation/pipeline.yaml from glue/tables.json,
so the 21 bronze jobs and the workflow's dependencies always match the table list.

Run from the repo root:  python3 tools/generate_pipeline.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
tables = json.loads((ROOT / "glue" / "tables.json").read_text())["tables"]


def logical_id(name):
    return "Bronze" + "".join(p.capitalize() for p in name.split("_")) + "Job"


SPARK_ARGS = """        --enable-glue-datacatalog: "true"
        --enable-metrics: "true"
        --enable-continuous-cloudwatch-log: "true"
        --job-language: python
        --extra-py-files: !Sub "s3://${LakehouseBucketName}/scripts/glue/lakehouse_utils.py"
        --lake_root: !Sub "s3://${LakehouseBucketName}\""""

out = ['''AWSTemplateFormatVersion: "2010-09-09"
Description: >
  Healthcare Metrics on AWS - pipeline. Google Drive ingestion job, one bronze
  job per table, silver and gold jobs, the Glue Workflow that schedules and
  orchestrates them, and the dashboard's read-only IAM user.
  GENERATED by tools/generate_pipeline.py from glue/tables.json - edit those, not this file.

Parameters:
  LakehouseBucketName:
    Type: String
    Default: peter-cms-lakehouse-2026
  DriveFolderId:
    Type: String
    Default: 1kBkROoSh7uU3Yu6I8AeF7EUx3bjhqJdc
    Description: Google Drive folder holding the source files.
  Release:
    Type: String
    Default: "2024-10"
    AllowedPattern: "^[0-9]{4}-(0[1-9]|1[0-2])$"
    Description: Data release (YYYY-MM) that ingested files are filed under.
  GoogleSecretId:
    Type: String
    Default: cms/google-drive-service-account
  Schedule:
    Type: String
    Default: "cron(0 11 5 * ? *)"
    Description: When the workflow runs (UTC). Default is the 5th of each month at 11:00 UTC.

Resources:

  # --- Ingestion ----------------------------------------------------------------

  IngestJob:
    Type: AWS::Glue::Job
    Properties:
      Name: cms-ingest-drive-to-s3
      Description: "Google Drive API -> s3://<bucket>/landing/<table>/release=<YYYY-MM>/"
      Role: !Sub "arn:aws:iam::${AWS::AccountId}:role/cms-lakehouse-glue-role"
      Command:
        Name: pythonshell
        PythonVersion: "3.9"
        ScriptLocation: !Sub "s3://${LakehouseBucketName}/scripts/glue/ingest_drive_to_s3.py"
      GlueVersion: "3.0"
      MaxCapacity: 1
      Timeout: 30
      MaxRetries: 0
      DefaultArguments:
        --additional-python-modules: "google-api-python-client==2.154.0,google-auth==2.36.0"
        --bucket: !Ref LakehouseBucketName
        --folder_id: !Ref DriveFolderId
        --release: !Ref Release
        --secret_id: !Ref GoogleSecretId
''']

out.append("  # --- Bronze: one job per table --------------------------------------------------\n")
for t in tables:
    out.append(f'''
  {logical_id(t["name"])}:
    Type: AWS::Glue::Job
    Properties:
      Name: cms-bronze-{t["name"].replace("_", "-")}
      Description: "landing/{t["name"]}/ CSV -> bronze/{t["name"]}/ Parquet"
      Role: !Sub "arn:aws:iam::${{AWS::AccountId}}:role/cms-lakehouse-glue-role"
      Command:
        Name: glueetl
        PythonVersion: "3"
        ScriptLocation: !Sub "s3://${{LakehouseBucketName}}/scripts/glue/bronze_table.py"
      GlueVersion: "5.0"
      WorkerType: G.1X
      NumberOfWorkers: 2
      Timeout: 20
      MaxRetries: 0
      DefaultArguments:
{SPARK_ARGS}
        --table: {t["name"]}
        --encoding: {t["encoding"]}
''')

for name, desc in (("Silver", "bronze -> silver (Spark SQL): rename, cast, clean"), ("Gold", "silver -> gold marts (Spark SQL)")):
    out.append(f'''
  {name}Job:
    Type: AWS::Glue::Job
    Properties:
      Name: cms-{name.lower()}
      Description: "{desc}"
      Role: !Sub "arn:aws:iam::${{AWS::AccountId}}:role/cms-lakehouse-glue-role"
      Command:
        Name: glueetl
        PythonVersion: "3"
        ScriptLocation: !Sub "s3://${{LakehouseBucketName}}/scripts/glue/{name.lower()}.py"
      GlueVersion: "5.0"
      WorkerType: G.1X
      NumberOfWorkers: 3
      Timeout: 30
      MaxRetries: 0
      DefaultArguments:
{SPARK_ARGS}
''')

bronze_actions = "\n".join(f"        - JobName: !Ref {logical_id(t['name'])}" for t in tables)
bronze_conditions = "\n".join(f"          - LogicalOperator: EQUALS\n            JobName: !Ref {logical_id(t['name'])}\n            State: SUCCEEDED" for t in tables)
out.append(f'''
  # --- Orchestration: Glue Workflow ------------------------------------------------

  Workflow:
    Type: AWS::Glue::Workflow
    Properties:
      Name: cms-lakehouse-pipeline
      Description: Monthly - ingest, bronze (21 jobs in parallel), silver, gold.
      MaxConcurrentRuns: 1

  StartTrigger:
    Type: AWS::Glue::Trigger
    Properties:
      Name: cms-start-monthly
      Type: SCHEDULED
      Schedule: !Ref Schedule
      StartOnCreation: true
      WorkflowName: !Ref Workflow
      Actions:
        - JobName: !Ref IngestJob

  BronzeTrigger:
    Type: AWS::Glue::Trigger
    Properties:
      Name: cms-after-ingest
      Type: CONDITIONAL
      StartOnCreation: true
      WorkflowName: !Ref Workflow
      Predicate:
        Conditions:
          - LogicalOperator: EQUALS
            JobName: !Ref IngestJob
            State: SUCCEEDED
      Actions:
{bronze_actions}

  SilverTrigger:
    Type: AWS::Glue::Trigger
    Properties:
      Name: cms-after-bronze
      Type: CONDITIONAL
      StartOnCreation: true
      WorkflowName: !Ref Workflow
      Predicate:
        Logical: AND
        Conditions:
{bronze_conditions}
      Actions:
        - JobName: !Ref SilverJob

  GoldTrigger:
    Type: AWS::Glue::Trigger
    Properties:
      Name: cms-after-silver
      Type: CONDITIONAL
      StartOnCreation: true
      WorkflowName: !Ref Workflow
      Predicate:
        Conditions:
          - LogicalOperator: EQUALS
            JobName: !Ref SilverJob
            State: SUCCEEDED
      Actions:
        - JobName: !Ref GoldJob

  # --- Dashboard: read-only IAM user (keys created in the console) ------------------

  DashboardUser:
    Type: AWS::IAM::User
    Properties:
      UserName: cms-dashboard-reader
      Policies:
        - PolicyName: athena-gold-read-only
          PolicyDocument:
            Version: "2012-10-17"
            Statement:
              - Sid: RunQueriesInOneWorkgroup
                Effect: Allow
                Action:
                  - athena:StartQueryExecution
                  - athena:GetQueryExecution
                  - athena:GetQueryResults
                  - athena:StopQueryExecution
                  - athena:GetWorkGroup
                Resource: !Sub "arn:aws:athena:${{AWS::Region}}:${{AWS::AccountId}}:workgroup/cms_lakehouse"
              - Sid: ReadGoldCatalog
                Effect: Allow
                Action:
                  - glue:GetDatabase
                  - glue:GetDatabases
                  - glue:GetTable
                  - glue:GetTables
                  - glue:GetPartition
                  - glue:GetPartitions
                Resource:
                  - !Sub "arn:aws:glue:${{AWS::Region}}:${{AWS::AccountId}}:catalog"
                  - !Sub "arn:aws:glue:${{AWS::Region}}:${{AWS::AccountId}}:database/cms_gold"
                  - !Sub "arn:aws:glue:${{AWS::Region}}:${{AWS::AccountId}}:table/cms_gold/*"
              - Sid: ReadGoldData
                Effect: Allow
                Action: s3:GetObject
                Resource: !Sub "arn:aws:s3:::${{LakehouseBucketName}}/gold/*"
              - Sid: QueryResults
                Effect: Allow
                Action:
                  - s3:GetObject
                  - s3:PutObject
                  - s3:AbortMultipartUpload
                Resource: !Sub "arn:aws:s3:::${{LakehouseBucketName}}/athena-results/*"
              - Sid: ListBucket
                Effect: Allow
                Action:
                  - s3:ListBucket
                  - s3:GetBucketLocation
                Resource: !Sub "arn:aws:s3:::${{LakehouseBucketName}}"

Outputs:
  WorkflowName:
    Value: !Ref Workflow
  DashboardUser:
    Value: !Ref DashboardUser
''')

path = ROOT / "infrastructure" / "cloudformation" / "pipeline.yaml"
path.write_text("".join(out))
print(f"wrote {path} with {len(tables)} bronze jobs")
